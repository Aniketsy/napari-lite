# napari-lite: own code
"""Write ``docs/shortcuts.md`` from the registered actions and default
shortcuts.

    python tools/make_shortcuts_doc.py

The table is built from ``napari_lite.utils.shortcuts.default_shortcuts``
(napari's defaults, copied) and the descriptions the layer and viewer
modules register with the action manager.  Mouse navigation is listed by
hand at the top.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'docs' / 'shortcuts.md'

HEADER = """# Keyboard and mouse

napari-lite keeps napari's default key bindings.  They are stored in
`get_settings().shortcuts.shortcuts` (action name -> list of shortcuts) and
can be changed in code for the session, before the first window is created:

```python
from napari_lite.settings import get_settings
from napari_lite.utils.action_manager import bind_shortcuts_from_settings

get_settings().shortcuts.shortcuts['napari:toggle_ndisplay'] = ['F3']
bind_shortcuts_from_settings()  # the viewer window does this too
```

`Ctrl` means `Cmd` on macOS.  Layer shortcuts work while that layer is the
active (selected) one.

## Mouse

| Action | 2D | 3D |
|---|---|---|
| Pan | drag | drag with Shift |
| Zoom | wheel | wheel |
| Rotate | | drag |
| Zoom to a box | Alt + drag | |
| Step through a slice dimension | Ctrl + wheel over the canvas | |
| Layer-specific tools (paint, pick, add point, draw shape) | click / drag in the layer's mode | |

"""

GROUP_TITLES = {
    'ViewerModel': 'Viewer',
}


def main() -> int:
    import importlib

    # importing these modules registers the viewer and layer actions
    importlib.import_module('napari_lite.components')
    importlib.import_module('napari_lite.layers')
    # napari-lite's versions of the console and shortcuts actions
    importlib.import_module('napari_lite.qt._viewer_actions')
    from napari_lite.utils.action_manager import action_manager
    from napari_lite.utils.interactions import Shortcut
    from napari_lite.utils.shortcuts import default_shortcuts

    groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for name, keys in default_shortcuts.items():
        action = action_manager._actions.get(name)
        if action is None:
            continue
        provider = action.keymapprovider
        group = GROUP_TITLES.get(
            provider.__name__ if provider else 'Other',
            provider.__name__ if provider else 'Other',
        )
        shortcuts = ', '.join(f'`{Shortcut(k)}`' for k in keys)
        groups[group].append((shortcuts, action.description, name))

    order = [
        'Viewer',
        'Image',
        'Labels',
        'Points',
        'Shapes',
        'Vectors',
        'Surface',
        'Tracks',
        'Other',
    ]
    lines = [HEADER]
    for group in [*order, *sorted(set(groups) - set(order))]:
        rows = groups.get(group)
        if not rows:
            continue
        lines.append(f'## {group}\n')
        lines.append('| Shortcut | Action | Name |')
        lines.append('|---|---|---|')
        for shortcuts, description, name in rows:
            lines.append(f'| {shortcuts} | {description} | `{name}` |')
        lines.append('')
    lines.append(
        '_Generated by `tools/make_shortcuts_doc.py`; '
        'edit the generator, not this file._\n'
    )
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    total = sum(len(v) for v in groups.values())
    print(f'wrote {OUT} ({total} shortcuts in {len(groups)} groups)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
